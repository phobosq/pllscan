typedef struct _PCI_DEVICE_INFO
{
	UCHAR Bus;
	UCHAR Device;
	UCHAR Function;

	USHORT VendorId;
	USHORT DeviceId;

	UCHAR ClassCode;
	UCHAR SubClass;

} PCI_DEVICE_INFO, *PPCI_DEVICE_INFO;

typedef struct _PCI_READ_CONFIG_REQUEST
{
	UCHAR Bus;
	UCHAR Device;
	UCHAR Function;

	UCHAR Offset;

	ULONG Value;

} PCI_READ_CONFIG_REQUEST, *PPCI_READ_CONFIG_REQUEST;

typedef struct _PORT_REQUEST
{
	USHORT Port;
	UCHAR Value;
} PORT_REQUEST, *PPORT_REQUEST;

typedef struct _PORT_WRITE_REQUEST
{
	USHORT Port;
	UCHAR Value;

} PORT_WRITE_REQUEST, *PPORT_WRITE_REQUEST;


typedef struct _SMBUS_READ_REQUEST
{
	UCHAR SlaveAddress;
	UCHAR Command;

	UCHAR Data;
	UCHAR Status;

} SMBUS_READ_REQUEST, *PSMBUS_READ_REQUEST;


typedef struct _SMBUS_WRITE_REQUEST
{
	UCHAR SlaveAddress;
	UCHAR Command;
	UCHAR Data;

} SMBUS_WRITE_REQUEST, *PSMBUS_WRITE_REQUEST;